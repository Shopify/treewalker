"""The paper's tables, regenerated from the final runs (`results`).

- Table 1 (`decomposition_table.tex`): v1's decomposition_validation.py table, the
  per-row work ratio of TreeWalker's two evaluators at T=500, L=8 on SUPPORT and
  FLCHAIN, LightGBM, from the ablation's counters.
- Tables 3 and 10 (`scenario_credit_<machine>.md`): v1's summarize_scenario.py,
  the credit what-if at T=500, L=8, LightGBM, over k and G. Its trace-evaluator
  columns (trace ratio, the (d_v+1)/(d+1) prediction, d_v) are dropped: the final
  run records the trace evaluator's counters only in the ablation suite, which has
  no what-if cell (the user's decision, 2026-10-08).
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import polars as pl

from . import figures, results

HORIZONS = (4, 16, 64, 128)


def decomposition_table(work: Any) -> str:
    w, asym = figures.decomposition(work)
    lgb = w.filter(pl.col("framework") == "lightgbm")
    body = []
    for ds in ("support", "flchain"):
        for ev, label in (("trace", "trace"), ("precompute", "precompute (default)")):
            g = lgb.filter((pl.col("dataset") == ds) & (pl.col("evaluator") == ev))
            by_h = {r["horizon"]: r["per_row_ratio"] for r in g.iter_rows(named=True)}
            cells = " & ".join(f"{by_h[h]:.3f}" if h in by_h else "--" for h in HORIZONS)
            body.append(
                f"  {ds.upper()} & {label} & {cells} & \\textit{{{asym[(ds, ev)]:.3f}}} \\\\"
            )
    rows = {
        ds: lgb.filter((pl.col("dataset") == ds) & (pl.col("evaluator") == "trace"))
        .sort("horizon")
        .select("horizon", "G")
        .rows()
        for ds in ("support", "flchain")
    }
    realized = ", ".join(f"{h} holds {g:.0f}" for h, g in rows["support"] if abs(g - h) >= 0.5)
    return rf"""% Auto-generated by treewalker-exp tables; do not hand-edit.
\begin{{table}}[h]
\centering
\small
\begin{{tabular}}{{llrrrrr}}
\toprule
& & \multicolumn{{4}}{{c}}{{Group size $G$}} & Asymptote \\
\cmidrule(lr){{3-6}}
Dataset & Evaluator & 4 & 16 & 64 & 128 & $G \to \infty$ \\
\midrule
{chr(10).join(body)}
\bottomrule
\end{{tabular}}
\caption{{Per-row work ratio $W(\mathcal{{F}}, X) / (G \cdot T \cdot L)$
at the reference configuration ($T=500$, $L=8$, LightGBM) on the fixed-$G$
datasets, swept across $G \in \{{4, 16, 64, 128\}}$; the counts are the same on
both machines. $G$ is the survival horizon; the work is divided by the rows a
group holds, which on SUPPORT fall short of long horizons (on average a horizon
of {realized} rows). The final column gives the Corollary~\ref{{cor:trace}}
asymptote under this baseline: $(d_v+1)/L$ for trace (with $d_v$ estimated from
\texttt{{partition\_row\_evals}} at the largest $G$) and $1/L$ for precompute.
Figure~\ref{{fig:asymptotic-convergence}} visualizes the same data.}}
\label{{tab:decomp-results}}
\end{{table}}
"""


def scenario_table(factorial: Any, work: Any, arch: str) -> str:
    """The credit what-if at T=500, L=8 (LightGBM), per k and G: TreeWalker's and
    the full walk's p50 per group, the speedup with its interval, and the default
    evaluator's work ratio."""
    sel = (
        (pl.col("dataset") == "credit")
        & (pl.col("framework") == "lightgbm")
        & (pl.col("T") == 500)
        & (pl.col("L") == 8)
        & (pl.col("family") == "whatif")
        & pl.col("replicate").is_null()
    )
    d = factorial.filter(sel & (pl.col("arch") == arch))
    tw = {r["cell"]: r for r in results.rows(d, "treewalker", "all-on").iter_rows(named=True)}
    fw = {r["cell"]: r for r in results.rows(d, "treewalker_fullwalk").iter_rows(named=True)}
    w = {
        r["cell"]: r
        for r in work.filter(sel & (pl.col("variant") == "all-on")).iter_rows(named=True)
    }
    lines = [
        f"# Credit what-if summary ({arch})",
        "",
        "Dataset: UCI Default of Credit Card Clients (OpenML 42477). Model: LightGBM T=500, "
        "L=8. Each cell: G scenarios for each base row, k perturbed features. Speedup: the "
        "full walk's time per row over TreeWalker's, row-weighted, with its 95% bootstrap "
        "interval. Work ratio: TreeWalker's work per group under the default (precompute) "
        "evaluator over G*T*L (asymptote 1/L). The trace evaluator's columns of v1 are not "
        "recorded for these cells.",
        "",
        "| k | G | TW p50 us/group | full walk p50 us/group | speedup | 95% interval "
        "| work ratio |",
        "|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for cell in sorted(tw, key=lambda c: (results.design(c)["k"], results.design(c)["G"])):
        k, g = tw[cell]["k"], tw[cell]["G"]
        f = fw[cell]
        ratio = "n/a"
        if cell in w:
            c = w[cell]
            total = (c["constant_steps"] + c["varying_splits"] + c["precompute_row_evals"]) / c[
                "groups"
            ] + (c["rows"] / c["groups"]) * 500
            ratio = f"{total / ((c['rows'] / c['groups']) * 500 * 8):.3f}"
        lines.append(
            f"| {k} | {g} | {tw[cell]['p50_us']:.2f} | {f['p50_us']:.2f} | {f['speedup']:.2f}x | "
            f"[{f['lo']:.2f}, {f['hi']:.2f}] | {ratio} |"
        )
    return "\n".join(lines) + "\n"


def generate(runs: Path, out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / "decomposition_table.tex").write_text(
        decomposition_table(results.work(runs, "ablation"))
    )
    print("  decomposition_table.tex", file=sys.stderr)
    factorial = results.speedups(runs, "factorial")
    work = results.work(runs, "factorial")
    for arch in results.MACHINES:
        (out / f"scenario_credit_{arch}.md").write_text(scenario_table(factorial, work, arch))
        print(f"  scenario_credit_{arch}.md", file=sys.stderr)
