"""Print the table of `src/predict/sigmoid.rs`: for j in 0..128, the relative remainder of
2^(j/128) from its nearest double H (the tail), and the bits of H less j << 45 and one
exponent (the scale's bits, to which the kernel adds its shifted k).

The standard library's decimal module computes them at 50 digits, so the script needs
nothing else; the result equals the table of Arm's optimized routines and glibc. The
output replaces the generated block of `src/predict/sigmoid.rs`:

    python3 experiments/scripts/sigmoid_table.py

With --vectors, it prints instead the margins and correctly rounded sigmoids of the
tests' `VECTORS`: the doubles at and beside the boundaries of the reduction's `kd`,
from the first table indices to the last and across `q`, and around the saturation
of `1 + e^-m`, for |m| <= 40.
"""

import math
import struct
import sys
from decimal import Decimal, getcontext

getcontext().prec = 50
N = 128


def bits(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def hex64(v: int) -> str:
    h = f"{v:016x}"
    return f"0x{h[:4]}_{h[4:8]}_{h[8:12]}_{h[12:]}"


def main() -> None:
    ln2 = Decimal(2).ln()
    print("// Generated by experiments/scripts/sigmoid_table.py.")
    print(f"static TABLE: [[u64; 2]; {N}] = [")
    for j in range(N):
        exact = (ln2 * j / N).exp()
        h = float(exact)
        tail = float((exact - Decimal(h)) / Decimal(h))
        scale = (bits(h) - (j << 45) - (1 << 52)) % 2**64
        print(f"    [{hex64(bits(tail))}, {hex64(scale)}],")
    print("];")


def vectors() -> None:
    ln2 = Decimal(2).ln()
    # t = -m crosses from kd to kd + 1 at (kd + 1/2) ln 2 / 128.
    kds = [0, 1, 63, 64, 126, 127, 128, 255, 1000, 4095, 6655, 7380]
    points = [float((kd + Decimal("0.5")) * ln2 / N) for kd in kds]
    points += [-p for p in points] + [0.0, 1.0, 36.0, 36.7, 37.0, 37.5, 40.0]
    points += [-p for p in (1.0, 36.0, 36.7, 37.0, 37.5, 40.0)]
    near = {
        m for p in points for m in (math.nextafter(p, -math.inf), p, math.nextafter(p, math.inf))
    }
    margins = sorted(m for m in near if abs(m) <= 40.0)
    print("// Generated by experiments/scripts/sigmoid_table.py --vectors.")
    print(f"const VECTORS: [[u64; 2]; {len(margins)}] = [")
    for m in margins:
        exact = 1 / (1 + (-Decimal(m)).exp())
        print(f"    [{hex64(bits(m))}, {hex64(bits(float(exact)))}],")
    print("];")


if __name__ == "__main__":
    if sys.argv[1:] == ["--vectors"]:
        vectors()
    else:
        main()
