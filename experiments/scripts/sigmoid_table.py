"""Print the table of `src/predict/sigmoid.rs`: for j in 0..128, the relative remainder of
2^(j/128) from its nearest double H (the tail), and the bits of H less j << 45 and one
exponent (the scale's bits, to which the kernel adds its shifted k).

The standard library's decimal module computes them at 50 digits, so the script needs
nothing else; the result equals the table of Arm's optimized routines and glibc. The
output replaces the generated block of `src/predict/sigmoid.rs`:

    python3 experiments/scripts/sigmoid_table.py
"""

import struct
from decimal import Decimal, getcontext

getcontext().prec = 50
N = 128


def bits(x: float) -> int:
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def hex64(v: int) -> str:
    h = f"{v:016x}"
    return f"0x{h[:4]}_{h[4:8]}_{h[8:12]}_{h[12:]}"


def main() -> None:
    ln2 = Decimal(2).ln()
    print("// Generated by experiments/scripts/sigmoid_table.py.")
    print(f"static TABLE: [[u64; 2]; {N}] = [")
    for j in range(N):
        exact = (ln2 * j / N).exp()
        h = float(exact)
        tail = float((exact - Decimal(h)) / Decimal(h))
        scale = (bits(h) - (j << 45) - (1 << 52)) % 2**64
        print(f"    [{hex64(bits(tail))}, {hex64(scale)}],")
    print("];")


if __name__ == "__main__":
    main()
