//! The sigmoid link, `1 / (1 + e^-m)`: the crate's own, so that every platform computes
//! the same bits, and branch-free, so that the finish's loop vectorizes. libm's `exp`
//! differs in its last bit between platforms and CPUs and is called one value at a time.
//!
//! `e^t`, `t = -m`, is the method of Arm's optimized routines, which glibc's `exp` is on
//! every Linux target. With `kd` the nearest integer to `128 t / ln 2`, `kd = 128 q + j`
//! and `r = t - kd ln 2 / 128` (`|r| <= ln 2 / 256`), `e^t = 2^q H_j (1 + tail_j + p(r))`:
//! `H_j` is the nearest double to `2^(j/128)`, `tail_j` its relative remainder, and `p` a
//! degree-5 minimax polynomial. [`TABLE`] holds each `j`'s tail and the bits of `H_j` less
//! `j << 45`, so that adding `kd`'s shifted bits sets the scale's exponent in one integer
//! add. Each step that can is an FMA, by `mul_add`: one rounding on every platform, an
//! instruction on AArch64 and at x86-64-v3 and v4, a software `fma` at x86-64's base
//! level, which a build that dispatches runs only on CPUs without FMA.
//!
//! Two departures serve the sigmoid. The table's exponents are one lower, so the kernel
//! computes `e^t / 2`, and `1 + e^t` is `fma(e^t / 2, 2, 1)`: exact, and overflowing to
//! inf exactly where `1 + e^t` does. And `t` is clamped to [-707, 709.79], past which no
//! output changes: below, `1 + e^t` rounds to 1; above, it overflows. The clamp is `max`
//! then `min`, which would map a NaN to a number; margins are never NaN, since the loader
//! rejects non-finite leaves, base scores and alphas.
//!
//! Against correctly rounded references (412,621 inputs over the whole range, the
//! boundaries of `kd` and the special values), `e^t` is correctly rounded in 99.92% and
//! within 1 ulp in the rest (Apple's libm: 99.84%). The sigmoid equals `1 / (1 + exp(-m))`
//! with Apple's libm in 99.92% of 10^8 margins in [-40, 40], the rest within 4 ulp, and as
//! accurate: within 2 ulp of the correctly rounded sigmoid for |m| <= 40, as libm's.
//!
//! The constants, the polynomial and the split of `ln 2 / 128` are those of Arm's
//! optimized-routines, `math/exp_data.c` with N = 128 and EXP_POLY_ORDER = 5 (MIT OR
//! Apache-2.0 WITH LLVM-exception); the table is generated by
//! `experiments/scripts/sigmoid_table.py`.

/// 1.5 * 2^52: adding it rounds to an integer, which the sum's low mantissa bits hold.
