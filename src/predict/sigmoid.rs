/// The sigmoid of each of `L` margins, lane by lane: the arithmetic of every loop below.
#[expect(clippy::many_single_char_names, reason = "the method's terms")]
#[expect(
    clippy::manual_clamp,
    reason = "max then min: one instruction each, no NaN select"
)]
#[inline(always)]
fn lanes<const L: usize>(m: [f64; L]) -> [f64; L] {
    let mut out = [0.0; L];
    for (o, m) in out.iter_mut().zip(m) {
        let t = (-m).max(-707.0).min(709.79);
        let z = t.mul_add(INV_LN2_N, SHIFT);
        let ki = z.to_bits();
        let kd = z - SHIFT;
        let r = kd.mul_add(NEG_LN2_LO_N, kd.mul_add(NEG_LN2_HI_N, t));
        let [tail, scale] = TABLE[(ki & 127) as usize];
        let scale = f64::from_bits(scale.wrapping_add(ki << 45));
        let r2 = r * r;
        let p = r.mul_add(C3, C2);
        let tmp = (r2 * r2).mul_add(r.mul_add(C5, C4), r2.mul_add(p, f64::from_bits(tail) + r));
        let half = scale.mul_add(tmp, scale);
        *o = 1.0 / half.mul_add(2.0, 1.0);
    }
    out
}

/// `1 / (1 + e^-m)` for one margin `m`, bit for bit as production's link applies it.
/// `m` is finite or infinite: a NaN margin, which no model produces, gives a number.
#[inline(always)]
pub fn sigmoid(m: f64) -> f64 {
    lanes([m])[0]
}

/// [`sigmoid`] of `pre(v)` for every value `v`. On AArch64 in pairs: NEON has no gather
/// for the table, so LLVM keeps the plain loop to one lane, and two lanes at hand
/// vectorize. Elsewhere the plain loop vectorizes at the target's width.
#[cfg(target_arch = "aarch64")]
#[inline(always)]
pub(super) fn sigmoid_inplace(slice: &mut [f64], pre: impl Fn(f64) -> f64) {
    let mut pairs = slice.chunks_exact_mut(2);
    for p in &mut pairs {
        let out = lanes([pre(p[0]), pre(p[1])]);
        p.copy_from_slice(&out);
    }
    for v in pairs.into_remainder() {
        *v = sigmoid(pre(*v));
    }
}

/// [`sigmoid`] of `pre(v)` for every value `v`, in a loop that vectorizes at the
/// target's width.
#[cfg(not(target_arch = "aarch64"))]
#[inline(always)]
pub(super) fn sigmoid_inplace(slice: &mut [f64], pre: impl Fn(f64) -> f64) {
    for v in slice {
        *v = sigmoid(pre(*v));
    }
}

#[cfg(test)]
mod tests {
    use super::{sigmoid, sigmoid_inplace};

    /// Ulps between two doubles, counted across zero.
    fn ulps(a: f64, b: f64) -> u64 {
        let key = |v: f64| {
            let b = v.to_bits() as i64;
            if b < 0 { i64::MIN - b } else { b }
        };
        key(a).abs_diff(key(b))
    }

    fn libm(m: f64) -> f64 {
        1.0 / (1.0 + (-m).exp())
    }

    /// Margins from -750 to 750, every table index at many offsets, each with its
    /// neighbours.
    fn margins() -> Vec<f64> {
        let step = std::f64::consts::LN_2 / 256.0 * 0.999_7;
        (0..(1500.0 / step) as u32)
            .map(|i| f64::from(i).mul_add(step, -750.0))
            .flat_map(|m| [m, m.next_up(), m.next_down()])
            .collect()
    }

    #[test]
    fn within_four_ulps_of_libms_sigmoid() {
        let worst = margins()
            .into_iter()
            .map(|m| (ulps(sigmoid(m), libm(m)), m))
            .max_by_key(|&(d, _)| d)
            .unwrap();
        assert!(worst.0 <= 4, "{} ulps at {:e}", worst.0, worst.1);
    }

    #[test]
    fn the_loop_computes_the_kernels_bits() {
        // Every length up to 9, for the pairs and the remainder, from many starts.
        let all = margins();
        let pre = |m: f64| m.mul_add(0.5, 0.25);
        for n in 0..10 {
            for start in (0..all.len() - n).step_by(7_919) {
                let mut v = all[start..start + n].to_vec();
                let want: Vec<u64> = v.iter().map(|&m| sigmoid(pre(m)).to_bits()).collect();
                sigmoid_inplace(&mut v, pre);
                assert_eq!(v.iter().map(|x| x.to_bits()).collect::<Vec<_>>(), want);
            }
        }
    }

    #[test]
    fn special_values_are_libms() {
        for m in [
            0.0,
            -0.0,
            1e-300,
            f64::INFINITY,
            f64::NEG_INFINITY,
            709.79,
            -709.79,
            707.5,
            -707.5,
            745.2,
            -745.2,
        ] {
            assert_eq!(sigmoid(m).to_bits(), libm(m).to_bits(), "sigmoid({m:e})");
        }
    }
}
